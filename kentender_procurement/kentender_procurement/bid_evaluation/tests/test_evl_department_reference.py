"""EVL-CHG-001 v0.7 §3, §6, §7.2, §8, §9.3 (D02-A, D02-NOT-RECORDED), EVL-A18
and EVL-A19; AUTH-ADR-001 v1.12 §4.8 — the department is read from the staff
home organisation unit and snapshotted at commit; a missing department never
blocks an appointment and is completed once; the appointment reference is
generated by the server, never entered.

`bench run-tests` has no rollback on this bench: each test restores the home
units it set."""

from __future__ import annotations

import re
import uuid
from typing import Any

import frappe

from kentender_core.services import staff_home_unit as home
from kentender_procurement.bid_evaluation.services import appointment, member_department, reads, report, roster, secretary
from kentender_procurement.bid_evaluation.services.errors import EvaluationError
from kentender_procurement.bid_evaluation.tests.support import AO, CHAIR, HOP, MEMBER, MEMBER_2, REPLACEMENT, SECRETARY
from kentender_procurement.bid_evaluation.tests.test_evl_committee import CommitteeCase
from kentender_procurement.bid_submission.tests.support import key

MEMBERS = [
	{"user": CHAIR, "capacity": "Chair"},
	{"user": MEMBER, "capacity": "Member"},
	{"user": MEMBER_2, "capacity": "Member"},
]


def unit(name: str) -> str:
	found = frappe.db.get_value("Organisation Unit", {"unit_name": name, "status": "Active"}, "name")
	assert found, f"the canonical world has no active unit named {name}"
	return found


class DepartmentCase(CommitteeCase):
	def setUp(self):
		super().setUp()
		self.hrmd = unit("Human Resources Management and Development")
		self.digital = unit("Digital Health")
		for who in (CHAIR, MEMBER, MEMBER_2, REPLACEMENT):
			previous = frappe.db.get_value("User", who, home.FIELD)
			self.addCleanup(lambda who=who, previous=previous: (frappe.db.set_value("User", who, home.FIELD, previous), frappe.db.commit()))
			frappe.db.set_value("User", who, home.FIELD, None)
		self.set_home(CHAIR, self.hrmd)
		self.set_home(MEMBER, self.digital)  # MEMBER_2 deliberately has none

	def set_home(self, who: str, organisation_unit: str) -> dict[str, Any]:
		frappe.set_user("Administrator")
		token = home.get_staff_home_organisation_unit(who)["token"]
		return home.set_staff_home_organisation_unit(user=who, organisation_unit=organisation_unit, expected_token=token, idempotency_key=f"test-home-{uuid.uuid4().hex}")

	def appoint_members(self, members=None, user=AO, k=None) -> dict[str, Any]:
		return appointment.appoint_committee(tender=self.name, members=members or MEMBERS, expected_version=self.evl_version(), idempotency_key=k or key(), user=user)

	def stored(self, who: str) -> dict[str, Any]:
		current = roster.current_appointment(self.evaluation)
		return next(m for m in current.members if m.member_user == who).as_dict()

	def history(self) -> list[dict[str, Any]]:
		doc = frappe.get_doc("Evaluation Case", self.evaluation)
		return report._committee(doc)["history"]


class TestDepartmentFromTheHomeUnit(DepartmentCase):
	def test_the_department_is_the_home_unit_name_and_a_supplied_one_is_ignored(self):
		out = self.appoint_members([{**MEMBERS[0], "department": "Typed by the browser"}, MEMBERS[1], MEMBERS[2]])
		self.assertTrue(out["ok"], out)
		self.assertEqual(self.stored(CHAIR)["department"], "Human Resources Management and Development")
		self.assertEqual(self.stored(MEMBER)["department"], "Digital Health")

	def test_a_person_with_no_home_unit_is_appointed_and_reads_not_recorded(self):
		out = self.appoint_members()
		self.assertTrue(out["ok"], out)  # department plays no part in eligibility
		self.assertEqual(self.stored(MEMBER_2)["department"] or "", "")
		committee = reads.committee(frappe.get_doc("Evaluation Case", self.evaluation))
		by_user = {m["user"]: m["department"] for m in committee["members"]}
		self.assertEqual(by_user[MEMBER_2], "Not recorded")
		self.assertEqual(by_user[CHAIR], "Human Resources Management and Development")

	def test_the_department_is_a_snapshot_a_later_transfer_never_rewrites(self):
		self.appoint_members()
		self.set_home(CHAIR, self.digital)
		self.assertEqual(self.stored(CHAIR)["department"], "Human Resources Management and Development")
		self.set_home(CHAIR, "")
		self.assertEqual(self.stored(CHAIR)["department"], "Human Resources Management and Development")

	def test_the_pick_list_offers_the_home_unit_not_the_first_role_assignment(self):
		rows = {r["user"]: r for r in reads.candidates(tender_reference=self.reference, user=AO, purpose="committee")}
		self.assertEqual(rows[CHAIR]["department"], "Human Resources Management and Development")
		self.assertEqual(rows[MEMBER]["department"], "Digital Health")
		self.assertEqual(rows[MEMBER_2]["department"], "")  # none recorded: the form shows Not recorded and its notice


class TestCompletingABlank(DepartmentCase):
	def test_a_blank_department_is_completed_once_when_a_home_unit_is_recorded(self):
		self.appoint_members()
		self.set_home(MEMBER_2, self.digital)
		row = self.stored(MEMBER_2)
		self.assertEqual(row["department"], "Digital Health")
		self.assertEqual(row["department_recorded_by"], "Administrator")
		self.assertTrue(row["department_recorded_at"])
		entries = [h for h in self.history() if h.get("kind") == "Department recorded"]
		self.assertEqual(len(entries), 1, entries)
		self.assertEqual((entries[0]["person"], entries[0]["department"], entries[0]["by"]), (frappe.db.get_value("User", MEMBER_2, "full_name"), "Digital Health", "Administrator"))

	def test_a_recorded_department_is_never_replaced_and_a_replay_does_nothing(self):
		self.appoint_members()
		self.set_home(MEMBER_2, self.digital)
		again = {"event": "StaffHomeUnitChanged", "user": MEMBER_2, "before": "", "after": self.hrmd, "after_name": "Human Resources Management and Development",
			"actor": "Administrator", "instant": frappe.utils.now_datetime(), "command_id": "replay"}
		member_department.on_home_unit_changed(again)
		self.set_home(MEMBER_2, self.hrmd)
		self.assertEqual(self.stored(MEMBER_2)["department"], "Digital Health")
		self.assertEqual(len([h for h in self.history() if h.get("kind") == "Department recorded"]), 1)

	def test_a_former_member_and_a_superseded_appointment_are_never_completed(self):
		self.appoint_members()
		for who in (CHAIR, MEMBER, MEMBER_2):
			self.evl_declare(who)
		self.set_home(REPLACEMENT, self.digital)
		out = appointment.replace_member(tender=self.name, outgoing=MEMBER_2, incoming={"user": REPLACEMENT}, reason="Replace the member.", expected_version=self.evl_version(),
			idempotency_key=key(), user=AO)
		self.assertTrue(out["ok"], out)
		self.set_home(MEMBER_2, self.hrmd)  # MEMBER_2 left the committee with no department recorded
		former = [m for a in frappe.get_all("Evaluation Appointment", filters={"evaluation_case": self.evaluation}, pluck="name")
			for m in frappe.get_doc("Evaluation Appointment", a).members if m.member_user == MEMBER_2]
		self.assertTrue(former and all(not (m.department or "") for m in former), [m.department for m in former])


class TestGeneratedReferences(DepartmentCase):
	def expected_base(self) -> tuple[str, str, str]:
		entity, year, seq = re.match(r"^TND-([A-Z0-9]+)-(\d{4})-(\d+)$", self.reference).groups()
		return entity, f"{int(seq):03d}", year

	def test_the_committee_reference_is_generated_from_the_tender_and_stored_with_the_officer_and_time(self):
		entity, seq, year = self.expected_base()
		out = self.appoint_members()
		self.assertTrue(out["ok"], out)
		current = roster.current_appointment(self.evaluation)
		self.assertEqual(current.appointment_reference, f"{entity}/EVAL/{seq}/{year}")
		self.assertEqual((current.appointed_by, current.change_kind), (AO, "Initial"))
		self.assertTrue(current.appointed_at)
		history = [h for h in self.history() if h.get("kind") == "Initial"]
		self.assertEqual(history[0]["reference"], f"{entity}/EVAL/{seq}/{year}")
		self.assertEqual(history[0]["by"], frappe.db.get_value("User", AO, "full_name"))

	def test_a_replacement_and_a_secretary_each_get_their_own_reference(self):
		entity, seq, year = self.expected_base()
		self.appoint_members()
		for who in (CHAIR, MEMBER, MEMBER_2):
			self.evl_declare(who)
		out = appointment.replace_member(tender=self.name, outgoing=MEMBER_2, incoming={"user": REPLACEMENT}, reason="Replace the member.", expected_version=self.evl_version(),
			idempotency_key=key(), user=AO)
		self.assertTrue(out["ok"], out)
		self.assertEqual(roster.current_appointment(self.evaluation).appointment_reference, f"{entity}/EVAL/{seq}/{year}-R1")
		by_office = frappe.db.get_value("Evaluation Secretary Appointment", {"evaluation_case": self.evaluation, "status": "Current"}, "appointment_reference")
		self.assertEqual(by_office, f"{entity}/EVAL/SEC/{seq}/{year}")  # recorded by the appointment itself
		sec = secretary.delegate_secretary(tender=self.name, secretary=SECRETARY, expected_version=self.evl_version(), idempotency_key=key(), user=HOP)
		self.assertTrue(sec["ok"], sec)
		again = frappe.db.get_value("Evaluation Secretary Appointment", {"evaluation_case": self.evaluation, "status": "Current"}, "appointment_reference")
		self.assertEqual(again, f"{entity}/EVAL/SEC/{seq}/{year}-R1")  # never reused

	def test_a_replay_returns_the_original_and_a_refused_action_leaves_no_reference(self):
		k, version = key(), self.evl_version()
		first = appointment.appoint_committee(tender=self.name, members=MEMBERS, expected_version=version, idempotency_key=k, user=AO)
		replay = appointment.appoint_committee(tender=self.name, members=MEMBERS, expected_version=version, idempotency_key=k, user=AO)
		self.assertEqual(replay, first)
		self.assertEqual(len(frappe.get_all("Evaluation Appointment", filters={"evaluation_case": self.evaluation})), 1)

	def test_a_refused_appointment_creates_no_appointment_and_no_reference(self):
		with self.assertRaises(EvaluationError):
			self.appoint_members([MEMBERS[0], MEMBERS[1]])  # two members: not 3 to 5
		self.assertEqual(frappe.get_all("Evaluation Appointment", filters={"evaluation_case": self.evaluation}), [])

	def test_no_appointment_command_takes_a_typed_reference(self):
		with self.assertRaises(TypeError):
			appointment.appoint_committee(tender=self.name, members=MEMBERS, appointment_reference="TYPED/1", expected_version=self.evl_version(), idempotency_key=key(), user=AO)
		with self.assertRaises(TypeError):
			secretary.delegate_secretary(tender=self.name, secretary=SECRETARY, appointment_reference="TYPED/2", expected_version=self.evl_version(), idempotency_key=key(), user=HOP)
