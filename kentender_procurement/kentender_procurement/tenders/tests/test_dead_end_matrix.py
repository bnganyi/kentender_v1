	def test_every_tender_state_leaves_every_reader_somewhere_to_go(self):
		failures: list[str] = []
		root = self._started()
		failures += self.check("Draft — Tender details", self.record(root.name))
		self._save(root)
		failures += self.check("Draft — review, no must-fix", self.review(root.name))
		submitted = lifecycle.submit_tender_for_approval(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		root.reload()
		failures += self.check("Awaiting procurement approval", self.review(root.name))
		lifecycle.return_tender_for_correction(tender=root.name, reason="Confirm whether manufacturer authorisation is necessary and update the supplier evidence requirement.", affected_task="Supplier and contract requirements", expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.HOPF, task=submitted["task"])
		root.reload()
		failures += self.check("Draft — returned for correction", self.record(root.name))
		submitted = lifecycle.submit_tender_for_approval(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		root.reload()
		approved = lifecycle.approve_tender_package(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.HOPF, task=submitted["task"])
		root.reload()
		failures += self.check("Approved — awaiting AO authorisation", self.publication_screen(root.name))
		publication.authorise_tender_publication(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.AO, task=approved["task"])
		root.reload()
		frappe.flags.kt_tenders_clock = "2027-05-15 07:55:00"
		for channel in CHANNELS[:2]:
			self._confirm(root, channel)
		failures += self.check("Publication authorised — 2 of 4 confirmed", self.publication_screen(root.name))
		for channel in CHANNELS[2:]:
			self._confirm(root, channel)
		root.reload()
		self.assertEqual(root.overall_status, "Published — open")
		failures += self.check("Published — open", self.record(root.name))

		# a non-material addendum through every status
		frappe.flags.kt_tenders_clock = "2027-05-20 08:30:00"
		root.reload()
		name = addenda.create_addendum_draft(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)["addendum"]["name"]
		root.reload()
		addenda.update_addendum_draft(tender=root.name, addendum=name, values=ADDENDUM, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		failures += self.check("Addendum — Draft", self.addendum(root.name, name))
		root.reload()
		addenda.submit_addendum_for_issue(tender=root.name, addendum=name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		failures += self.check("Addendum — Awaiting issue", self.addendum(root.name, name))
		root.reload()
		addenda.issue_addendum(tender=root.name, addendum=name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.HOPF)
		failures += self.check("Addendum — Awaiting publication confirmation", self.addendum(root.name, name))
		for channel in CHANNELS:
			self._confirm(root, channel, subject="addendum", addendum=name)
		self.assertEqual(frappe.db.get_value("Tender Addendum", name, "status"), "Issued")
		failures += self.check("Addendum — Issued", self.addendum(root.name, name))

		# a supplier clarification from a registered candidate
		frappe.flags.kt_tenders_notice_sync = True
		frappe.flags.kt_tenders_notice_transport = lambda notice: {"result": "Delivered", "provider_reference": f"test:{notice.name}", "failure_reason": ""}
		self.addCleanup(setattr, frappe.flags, "kt_tenders_notice_sync", False)
		self.addCleanup(setattr, frappe.flags, "kt_tenders_notice_transport", None)
		candidate_gateway.register_stand_in_candidate(tender=root.name, user=fx.PRODUCER, bidder_arrangement_id="ARR-TNDT-001", candidate_name="Afya Digital Supplies Limited", notice_address="tenders@afyadigital.example")
		frappe.flags.kt_tenders_clock = "2027-05-26 09:00:00"
		received = clarifications.receive_tender_clarification(tender=root.name, candidate_registration_id="ARR-TNDT-001", question="May the two comparable contracts be from different customers?", received_at="2027-05-26 09:00:00", inbound_event_id="EVT-MATRIX-1", user=fx.PRODUCER)
		failures += self.check("Clarification — Awaiting response", self.clarification(root.name, received["clarification"]))
		failures += self.check("Published — open, clarification pending", self.record(root.name))
		root.reload()
		frappe.flags.kt_tenders_clock = "2027-05-26 11:00:00"
		clarifications.respond_to_tender_clarification(tender=root.name, clarification=received["clarification"], response="Yes. The two comparable contracts may be from different customers.", response_audience="All registered candidates", affects_published_tender=False, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		failures += self.check("Clarification — Answered", self.clarification(root.name, received["clarification"]))

		# a material proposal and its cancellation review
		frappe.flags.kt_tenders_clock = "2027-05-28 10:00:00"
		root.reload()
		material = addenda.create_addendum_draft(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)["addendum"]["name"]
		root.reload()
		addenda.update_addendum_draft(tender=root.name, addendum=material, values={**ADDENDUM, "affected_reference_key": "goods:1:quantity", "revised_value": "300 Each", "reason": "Additional deployment sites require 50 more laptops"}, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		failures += self.check("Addendum — material change, Draft", self.addendum(root.name, material))
		root.reload()
		addenda.request_tender_cancellation_review(tender=root.name, addendum=material, reason="Additional deployment sites require 50 more laptops; please consider cancellation.", expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.OFFICER)
		failures += self.check("Addendum — cancellation review requested", self.addendum(root.name, material))
		failures += self.check("Cancel Tender — review requested", self.cancellation_screen(root.name))

		# cancellation
		frappe.flags.kt_tenders_clock = "2027-06-04 14:00:00"
		root.reload()
		cancellation.cancel_tender(tender=root.name, ground="INADEQUATE_BUDGET", reason="The confirmed budget available for this procurement is insufficient to proceed.", expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.AO)
		failures += self.check("Cancelled — obligations due", self.cancellation_screen(root.name))
		failures += self.check("Cancelled — record", self.record(root.name))
		self.assertEqual(failures, [], "\n".join(failures))

	def test_segregation_and_requisition_correction_leave_no_dead_end(self):
		failures: list[str] = []
		# the combined-responsibility person prepared and submitted: another
		# HOPF and another AO hold the decisions and are named
		root = self._started(officer=fx.BOTH)
		self._save(root, officer=fx.BOTH)
		submitted = lifecycle.submit_tender_for_approval(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.BOTH)
		root.reload()
		failures += self.check("Awaiting procurement approval — preparer holds HOPF", self.review(root.name))
		# §10.7: the conflicted HOPF waits on the eligible one and is told why, in the one line
		step = read.get_tender_review(tender=root.name, user=fx.BOTH)["guidance"]["next_step"]
		self.assertEqual((step["kind"], step["sentence"]), (ns.KIND_WAITING, "You cannot approve a Tender Version you prepared or submitted."))
		approved = lifecycle.approve_tender_package(tender=root.name, expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.HOPF, task=submitted["task"])
		root.reload()
		failures += self.check("Approved — preparer holds AO", self.publication_screen(root.name))
		self.assertTrue(approved["task"])

		# a Requisition correction on a Draft
		fx.wipe_all()
		root = self._started()
		correction.request_requisition_correction(tender=root.name, reason="The authorised battery-runtime requirement must be corrected before this Tender can continue.", expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.HOPF)
		failures += self.check("Requisition correction requested", self.record(root.name))
		self.assertEqual(failures, [], "\n".join(failures))

	def test_the_departmental_author_sees_who_is_correcting_the_requisition(self):
		root = self._started()
		correction.request_requisition_correction(tender=root.name, reason="The authorised battery-runtime requirement must be corrected before this Tender can continue.", expected_record_version=root.record_version, idempotency_key=fx.key(), user=fx.HOPF)
		author = frappe.db.get_value("Requisition Version", frappe.db.get_value("Tender", root.name, "requisition_version"), "prepared_by")
		step = read.get_tender(tender=root.name, user=fx.OFFICER)["guidance"]["next_step"]
		self.assertEqual(step["kind"], ns.KIND_WAITING)
		self.assertIn(frappe.db.get_value("User", author, "full_name"), step["holder"]["people"])
		self.assertTrue(step["headline"].endswith(".") and "is correcting the requisition" in step["headline"])
		journey = read.get_tender(tender=root.name, user=fx.OFFICER)["guidance"]["journey"]
		self.assertEqual([s["marker"] for s in journey["stages"]][0], "blocked")
