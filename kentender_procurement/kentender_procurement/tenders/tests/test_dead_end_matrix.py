"""KT-STD-001 v1.8 §3B.7 / TPR-CHG-001 v0.12 §5.9 — the Tenders dead-end
matrix (plan Phase 2; TPR12-AC-001..010).

One Tender is walked with real commands through every §5.9 state its
lifecycle reaches — Draft (editor and review), returned and resubmitted,
HOPF approval, AO authorisation, publication part-confirmed, Published —
open, an addendum at each status, a material addendum and its cancellation
review, a supplier clarification, and Cancelled — plus a Requisition
correction and a segregation walk in which one person prepared the Tender.
At each state every reader reads the screen that state opens on, and for
every row:

1. the reader has a next step naming a holder and a reason, or an action
   (`kentender_core.services.next_step.problems`);
2. every blocker carries a reason code and a fix (same helper);
3. every route fix opens a Tenders task or page;
4. the next step's stage is the stage the tracker shows as current;
5. no reader is told to wait for themselves;
6. a technical reader never gets a turn (§3B.6).

The matrix is written to
`docs/mvp-1-r1/11_tenders/evidence/v0_12/dead_end_matrix.md`.
"""

