	def _read(self, fn, user):
		try:
			return fn(user)
		except (frappe.PermissionError, frappe.DoesNotExistError, TendersError):
			return None

	def check(self, state: str, fn) -> list[str]:
		failures = []
		for reader, user in READERS:
			view = self._read(fn, user)
			if view is None or view.get("outcome") not in (None, "OK"):
				self.rows.append((state, reader, "—", "cannot read this record", "pass"))
				continue
			guidance = view.get("guidance") or {}
			step = guidance.get("next_step")
			journey = guidance.get("journey") or {}
			problems = ns.problems(step)
			for fix in [f for b in (step or {}).get("blockers") or [] for f in b.get("fixes") or []] + list((step or {}).get("fixes") or []):
				if fix.get("kind") != ns.FIX_ROUTE:
					continue
				target = fix.get("target")
				if isinstance(target, dict):
					if target.get("task") not in TASK_ROUTES:
						problems.append(f"fix {fix.get('fix_id')} opens no Tender task")
				elif not target or target[0] not in PAGES:
					problems.append(f"fix {fix.get('fix_id')} opens no Tenders page")
			kind = (step or {}).get("kind", "")
			current = journey.get("current")
			if kind in (*TURNS, ns.KIND_WAITING) and current and step.get("stage") and step["stage"] != current:
				problems.append(f"stage {step['stage']} is not the tracker's {current}")
			if kind == ns.KIND_WAITING and frappe.db.get_value("User", user, "full_name") in ((step.get("holder") or {}).get("people") or []):
				problems.append("the reader is told to wait for themselves")
			if user == "Administrator" and kind in TURNS:
				problems.append("a technical reader was given a turn")
			if not journey.get("stages"):
				problems.append("no journey")
			result = "pass" if not problems else "FAIL: " + "; ".join(problems)
			if problems:
				failures.append(f"{state} / {reader}: {'; '.join(problems)}")
			self.rows.append((state, reader, kind or "none", (step or {}).get("headline") or "—", result))
		return failures

	def record(self, name):
		return lambda user: read.get_tender(tender=name, user=user)

	def review(self, name):
		return lambda user: read.get_tender_review(tender=name, user=user)

	def publication_screen(self, name):
		return lambda user: publication.get_tender_publication(tender=name, user=user)

	def addendum(self, name, addendum):
		return lambda user: open_period_read.get_tender_addendum(tender=name, addendum=addendum, user=user)

	def clarification(self, name, clarification):
		return lambda user: open_period_read.get_tender_clarification(tender=name, clarification=clarification, user=user)

	def cancellation_screen(self, name):
		return lambda user: open_period_read.get_tender_cancellation(tender=name, user=user)

	# ------------------------------------------------------------------

	def _started(self, officer=fx.OFFICER):
		authorised = fx.authorised_handoff()
		started = cmd.start_tender(handoff=authorised["handoff"], idempotency_key=fx.key(), user=officer)
		return frappe.get_doc("Tender", started["tender"])

	def _save(self, root, officer=fx.OFFICER):
		cmd.save_tender_draft(tender=root.name, values=sample.officer_values(inspection_location=fx.LOCATION, contact_office=fx.CONTACT_OFFICE), expected_record_version=root.record_version, idempotency_key=fx.key(), user=officer)
		root.reload()

	def _confirm(self, root, channel, *, subject="publication", addendum=""):
		root.reload()
		online = channel in configuration_gateway.ONLINE_CHANNELS
		common = dict(available_at="2027-05-15 08:00:00", evidence_reference=f"REF-{channel}", evidence_file=fx.evidence_file(f"{channel}.png"), public_url=f"https://portal.example.test/{channel}" if online else "", url_not_applicable_reason="" if online else "Physical channel", expected_record_version=root.record_version, idempotency_key=fx.key(), attestation_confirmed=True, user=fx.HOPF)
		if subject == "publication":
			return publication.confirm_publication_channel(tender=root.name, channel=channel, package_digest=frappe.db.get_value("Tender Publication", root.publication, "package_digest"), **common)
		return addenda.confirm_addendum_publication_channel(tender=root.name, addendum=addendum, channel=channel, addendum_digest=frappe.db.get_value("Tender Addendum", addendum, "addendum_digest"), **common)

